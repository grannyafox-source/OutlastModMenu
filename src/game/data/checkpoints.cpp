bool IsDlcCheckpoint(const std::string& name) {
    for (const Chapter& c : Chapters())
        for (const Checkpoint& cp : c.checkpoints)
            if (str::IEquals(cp.name, name)) return c.dlc;
    return str::IStartsWith(name, "DLC_");
}

